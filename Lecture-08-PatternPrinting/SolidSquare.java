public class SolidSquare {
    public static void main(String[] args) {
        
    int n=4;

    for (int row=1; row<=n; row ++){
        // For each row n coloumns
        for( int col=1; col<=n; col ++){
            System.out.print("* ");
        }
        //Move to next line
        System.out.println();

    }
}
}
 
     