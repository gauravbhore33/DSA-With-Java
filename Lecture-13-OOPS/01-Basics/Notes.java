// 🔥 Very important interview comparison

// You should eventually be able to answer this without thinking:

// Concept	Main purpose
// Encapsulation	Protect/control data
// Abstraction	Hide implementation complexity
// Inheritance	Reuse/extend behavior
// Polymorphism	Same interface/reference, different behavior

// And:

// Overloading	Overriding
// Same class usually	Parent-child relationship
// Different parameters	Same signature
// Compile time	Runtime
// Return type alone cannot differ	Covariant return possible
// Static methods can be overloaded	Static methods are hidden, not overridden
// 🎯 How YOU should answer "Explain OOP"

// Don't give a 30-second memorized definition.

// Give this structure:

// Step 1 — Definition

// "OOP stands for Object-Oriented Programming. It is a programming paradigm where we organize software around objects that combine state and behavior."

// Step 2 — Why

// "It helps us structure large applications into reusable and maintainable components."

// Step 3 — Four pillars

// "The four main principles are encapsulation, inheritance, polymorphism and abstraction."

